import { createHash } from "node:crypto";
import type { Plugin } from "vite";
import { NETWORK_ONLY_PREFIXES } from "./src/shared/pwa/swStrategy.ts";

const CACHE_PREFIX = "omeg4mon-router-";

const CORE_PRECACHE_URLS = [
  "/index.html",
  "/manifest.webmanifest",
  "/icon.svg",
  "/favicon.ico",
  "/icons/pwa-192x192.png",
  "/icons/pwa-512x512.png",
  "/icons/pwa-maskable-512x512.png",
] as const;

export function buildServiceWorkerSource(
  cacheName: string,
  precacheUrls: readonly string[],
): string {
  const uniqueUrls = Array.from(new Set(precacheUrls)).sort();
  return `// Auto-generated by omeg4monPwaPlugin at build time.
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(uniqueUrls, null, 2)};
const NETWORK_ONLY_PREFIXES = ${JSON.stringify(NETWORK_ONLY_PREFIXES)};

function isNetworkOnlyPath(pathname) {
  if (pathname === "/sw.js") {
    return true;
  }
  for (const prefix of NETWORK_ONLY_PREFIXES) {
    if (pathname === prefix || pathname.startsWith(prefix + "/")) {
      return true;
    }
  }
  return false;
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS)),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") {
    return;
  }

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) {
    return;
  }
  if (isNetworkOnlyPath(url.pathname)) {
    return;
  }

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok && response.type === "basic") {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put("/index.html", copy));
          }
          return response;
        })
        .catch(() =>
          caches
            .open(CACHE_NAME)
            .then((cache) => cache.match("/index.html"))
            .then((cached) => cached || Response.error()),
        ),
    );
    return;
  }

  event.respondWith(
    caches.open(CACHE_NAME).then((cache) =>
      cache.match(request).then((cached) => {
        if (cached) {
          return cached;
        }
        return fetch(request).then((response) => {
          if (response.ok && response.type === "basic") {
            cache.put(request, response.clone());
          }
          return response;
        });
      }),
    ),
  );
});
`;
}

export function omeg4monPwaPlugin(): Plugin {
  return {
    name: "omeg4mon-pwa-sw",
    apply: "build",
    generateBundle(_options, bundle) {
      const emittedAssetUrls: string[] = [];
      for (const fileName of Object.keys(bundle)) {
        if (fileName.startsWith("assets/")) {
          emittedAssetUrls.push(`/${fileName}`);
        }
      }
      const precacheUrls = [...CORE_PRECACHE_URLS, ...emittedAssetUrls].sort();
      const digest = createHash("sha256")
        .update(precacheUrls.join("\n"))
        .digest("hex")
        .slice(0, 12);
      const cacheName = `${CACHE_PREFIX}v1-${digest}`;
      const source = buildServiceWorkerSource(cacheName, precacheUrls);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source,
      });
    },
  };
}
